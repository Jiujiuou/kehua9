// 关键词索引：用于快速查找情绪词
// 格式: { word: { emotionId, baseIntensity } }
export const KEYWORD_INDEX = (() => {
  const index = {};

  // 遍历所有情绪类别，构建索引
  Object.keys(EMOTION_KEYWORDS).forEach(emotionId => {
    const keywords = EMOTION_KEYWORDS[emotionId];
    const category = EMOTION_CATEGORIES[emotionId];

    if (!category) {
      console.warn(`[KEYWORD_INDEX] 警告: 找不到情绪类别 ${emotionId}`);
      return;
    }

    keywords.forEach(keyword => {
      // 根据情绪类别的强度范围计算基础强度
      const [minIntensity, maxIntensity] = category.intensityRange;
      const baseIntensity = (minIntensity + maxIntensity) / 2;

      // 如果关键词已存在，保留强度更高的
      if (index[keyword]) {
        if (baseIntensity > index[keyword].baseIntensity) {
          index[keyword] = {
            emotionId,
            baseIntensity
          };
        }
      } else {
        index[keyword] = {
          emotionId,
          baseIntensity
        };
      }
    });
  });

  return index;
})();